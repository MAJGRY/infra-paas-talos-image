#!/usr/bin/env bash
# Pins everything the build pulls to a digest: the Talos imager, the base installer and the
# extension images that the Talos release itself lists (ghcr.io/siderolabs/extensions image,
# file image-digests). Writes image.lock.
#
#   hack/resolve.sh          rewrite image.lock from image.env
#   hack/resolve.sh --check  fail when image.lock is not what image.env resolves to (CI)
#
# Needs crane (hack/install-crane.sh).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
# shellcheck source=../image.env
source "${ROOT}/image.env"
: "${TALOS_VERSION:?image.env: TALOS_VERSION is empty}" "${EXTENSIONS:?image.env: EXTENSIONS is empty}"

check=false
case "${1:-}" in
  --check) check=true ;;
  "") ;;
  *) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac

pin() { # image:tag -> image:tag@digest
  echo "$1@$(crane digest "$1")"
}

imager="$(pin "ghcr.io/siderolabs/imager:${TALOS_VERSION}")"
base="$(pin "ghcr.io/siderolabs/installer-base:${TALOS_VERSION}")"
extensions="$(pin "ghcr.io/siderolabs/extensions:${TALOS_VERSION}")"
digests="$(crane export --platform linux/amd64 "${extensions}" - | tar -xO image-digests)"

refs=""
for name in ${EXTENSIONS}; do
  ref="$(grep -E "^ghcr\.io/siderolabs/${name}:[^@]+@sha256:[0-9a-f]{64}$" <<<"${digests}" || true)"
  if [[ -z "${ref}" || "$(wc -l <<<"${ref}")" -ne 1 ]]; then
    echo "resolve: extension ${name} is not listed exactly once in ${extensions}" >&2
    exit 1
  fi
  refs+="${ref}"$'\n'
done

lock="$(mktemp)"
trap 'rm -f "${lock}"' EXIT
cat >"${lock}" <<EOF
# Generated by hack/resolve.sh from image.env. Do not edit by hand.
IMAGER_IMAGE=${imager}
INSTALLER_BASE_IMAGE=${base}
EXTENSIONS_IMAGE=${extensions}
EXTENSION_IMAGES="
${refs}"
EOF

if ${check}; then
  if ! diff -u "${ROOT}/image.lock" "${lock}"; then
    echo "resolve: image.lock is out of date, run hack/resolve.sh and commit the result" >&2
    exit 1
  fi
  echo "resolve: image.lock is up to date"
else
  cp "${lock}" "${ROOT}/image.lock"
  echo "resolve: wrote image.lock"
fi
